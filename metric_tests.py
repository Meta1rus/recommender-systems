"""Тесты метрик для ДЗ №1 (lab2).

Оригинального файла metric_tests.py из материалов курса не было, поэтому тесты написаны
самостоятельно строго по формулам из условия задания:

    AP_u@k = 1 / min(k, n_u) * sum_{i=1..k} r_u(i) * p_u@i,     p_u@k = 1/k * sum_{j=1..k} r_u(j)
    RR@k   = 1 / rank_i@k  (позиция первого релевантного среди первых k; 0, если его нет)
    HR@k   = [есть хотя бы одно релевантное среди первых k]
    если topn не задан, k = n_u (число айтемов юзера в тесте).

Все ожидаемые значения посчитаны вручную (в комментариях).
"""
import numpy as np

# (gt_items, predictions, topn, (AP, RR, HR))
CASES = [
    # r = [1, 0, 1]: AP = (1/1 + 2/3) / min(3, 2) = 0.8333; первое попадание на 1-й позиции
    ([1, 2], [1, 3, 2], 3, ((1 + 2 / 3) / 2, 1.0, 1.0)),
    # topn не задан -> k = n_u = 2: смотрим [1, 3], r = [1, 0]: AP = 1 / 2
    ([1, 2], [1, 3, 2], None, (0.5, 1.0, 1.0)),
    # k = n_u = 1: смотрим только [1] — попаданий нет
    ([5], [1, 5, 2], None, (0.0, 0.0, 0.0)),
    # k = 3: r = [0, 1, 0]: AP = (1/2) / min(3, 1) = 0.5, RR = 1/2
    ([5], [1, 5, 2], 3, (0.5, 0.5, 1.0)),
    # нет пересечения
    ([1, 2, 3], [4, 5, 6], None, (0.0, 0.0, 0.0)),
    # идеальная выдача
    ([1, 2, 3], [1, 2, 3], None, (1.0, 1.0, 1.0)),
    # порядок релевантных внутри топа не важен для AP, если они идут первыми
    ([7, 8], [8, 7, 1, 2], 4, (1.0, 1.0, 1.0)),
    # релевантное на 3-й позиции: AP = (1/3) / 1, RR = 1/3
    ([3], [1, 2, 3, 4, 5], 5, (1 / 3, 1 / 3, 1.0)),
    # тот же случай, но k = 2 — релевантное не попадает в топ
    ([3], [1, 2, 3, 4, 5], 2, (0.0, 0.0, 0.0)),
    # AP зависит от порядка: r = [0, 1, 1] -> (1/2 + 2/3) / 2
    ([1, 2], [3, 1, 2], 3, ((1 / 2 + 2 / 3) / 2, 0.5, 1.0)),
    # topn больше длины списка предсказаний: r = [0, 1], AP = (1/2) / min(10, 2)
    ([1, 2], [3, 1], 10, (0.25, 0.5, 1.0)),
    # numpy-массивы на входе
    (np.array([10, 20, 30]), np.array([30, 40, 10, 50]), 4, ((1 + 2 / 3) / 3, 1.0, 1.0)),
]


def run_tests(ap_metric, rr_metric, hr_metric):
    failed = 0
    for n, (gt, preds, topn, (ap, rr, hr)) in enumerate(CASES, 1):
        got = (ap_metric(gt, preds, topn), rr_metric(gt, preds, topn), hr_metric(gt, preds, topn))
        for name, g, e in zip(('AP', 'RR', 'HR'), got, (ap, rr, hr)):
            if g is None or not np.isclose(float(g), e):
                failed += 1
                print(f'тест {n}: {name}(gt={list(gt)}, preds={list(preds)}, topn={topn}) = {g}, ожидалось {e:.6f}')
    if failed:
        raise AssertionError(f'не пройдено проверок: {failed}')
    print(f'Все тесты пройдены: {len(CASES)} случаев x 3 метрики')
